test("a hunk whose context holds a line separator character is still parsed", () => {
  for (const separator of [" ", " ", "\r"]) {
    const lines = [`@@ -1 +1 @@ function a${separator}b() {`, "-old", "+new"];
    const section = parseSection(["diff --git a/x.js b/x.js", "--- a/x.js", "+++ b/x.js", ...lines]);
    assert.equal(section.hunks.length, 1, JSON.stringify(separator));
    assert.equal(section.hunks[0].added, 1);
  }
});

