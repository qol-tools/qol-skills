const JOBS = CORE_LENSES.map((lens) => ({ id: `c01-${lens}-p1`, kind: "finder", lenses: [lens], pass: 1, chunk: "c01" }));

function composeState(finderCandidate, verdict) {
  const scope = {
    run_id: "r",
    target: { kind: "commit", input: "HEAD" },
    base: { ref: "HEAD^", sha: "2".repeat(40) },
    head: { ref: "HEAD", sha: "1".repeat(40), snapshot: false },
    pr: null,
    level: { used: "standard" },
    plan: { solo: false, verify: "agent", lenses: CORE_LENSES, jobs: JOBS },
    files: [{ path: "src/app.js", old_path: null, tier: "medium", excluded: false, exclude_reason: null, status: "M", added_runs: [[10, 12]] }],
  };
  const finds = new Map(JOBS.map((item) => [item.id, { job: item.id, candidates: item.id === "c01-correctness-p1" ? [finderCandidate] : [], files_read: [{ path: "src/app.js", read: "full" }], declined: [], agent_id: `agent-${item.id}` }]));
  const candidates = mergeCandidates({ jobs: JOBS, outputs: finds, check: () => null, verifierCap: 30, final: true });
  const verdicts = new Map([["G01", { group: "G01", status: "confirmed", confidence: "high", checked: ["read src/app.js:10"], agent_id: "agent-verify-G01", ...verdict }]]);
  const run = { runtime: "claude-code", mode: "multi-agent" };
  const review = (extra) => ({ verdict: "block", run, findings: [{ groups: ["G01"] }], dropped: [], claims: [], coverage: { files: [], not_reviewed: [], executed: [] }, ...extra });
  return { compose: (extra) => composeReview({ scope, candidates, verdicts, finds, review: review(extra), intent: null, check: () => null }) };
}

const high = (extra = {}) => candidate({ severity: "high", locations: [{ file: "src/app.js", line: 10 }], ...extra });
const conflict = { claims: ["verify-G01 confirmed it", "the session disagrees"], resolution: "src/app.js:9 guards the call" };

test("a finder's pre_existing claim on added lines does not take a confirmed high out of the verdict", () => {
  const { compose } = composeState(high({ pre_existing: true }), {});
  const { report, problems } = compose({});
  assert.deepEqual(problems, []);
  assert.equal(report.findings[0].pre_existing, false);
  assert.equal(report.verdict, "block");
});

test("a verifier can mark a defect pre-existing, but not one on added lines", () => {
  const off = composeState(high({ locations: [{ file: "src/app.js", line: 30 }] }), { pre_existing: true }).compose({ verdict: "pass" });
  assert.deepEqual(off.problems, []);
  assert.equal(off.report.findings.length, 0);
  assert.equal(off.report.pre_existing.length, 1);
  const added = composeState(high(), { pre_existing: true }).compose({ verdict: "pass" });
  assert.ok(added.problems.some((problem) => /added lines are introduced by this change/.test(problem)), added.problems.join("\n"));
});

test("a verifier-confirmed group cannot be dropped, downgraded or marked pre-existing without a conflict block", () => {
  const { compose } = composeState(high(), {});
  const needs = (problems) => assert.ok(problems.some((problem) => /needs a conflict block/.test(problem)), problems.join("\n"));
  needs(compose({ verdict: "pass", findings: [], dropped: [{ group: "G01", reason: "I disagree" }] }).problems);
  needs(compose({ verdict: "conditional", findings: [{ groups: ["G01"], severity: "medium", severity_reason: "minor" }] }).problems);
  needs(compose({ verdict: "conditional", findings: [{ groups: ["G01"], status: "needs_verification", confidence: "low" }] }).problems);
  needs(compose({ verdict: "pass", findings: [{ groups: ["G01"], pre_existing: true }] }).problems);
  assert.deepEqual(compose({ verdict: "pass", findings: [], dropped: [{ group: "G01", reason: "I disagree", conflict }] }).problems, []);
  assert.deepEqual(compose({ verdict: "conditional", findings: [{ groups: ["G01"], severity: "medium", severity_reason: "minor", conflict }] }).problems, []);
});

const INTENT = { source: "stated", summary: "Grow the file. Nothing else changes.", requirements: [], claims: [] };

function scoped(name, files = { "src/app.js": numbered(60) }, options = { level: "standard" }) {
  const dir = makeRepo(root, name);
  commit(dir, { "src/app.js": numbered(20) }, "base");
  const head = commit(dir, files, "change");
  return runScope(head, options, depsFor(dir, path.join(root, `${name}-out`)));
}

const file = (scope, name) => path.join(scope.run_dir, name);
const step = (scope) => {
  try {
    return runNext(scope.run_dir, { env: ENV });
  } catch (error) {
    return error.report ?? { error: error.message };
  }
};

test("next recomputes the merge, so a rewritten candidates.json changes nothing", () => {
  const scope = scoped("tamper");
  writeJson(file(scope, "intent.json"), INTENT);
  writeFinds(scope, { "c01-correctness-p1": [candidate({ severity: "high", confidence: "high", locations: [{ file: "src/app.js", line: 30 }] })] });
  assert.deepEqual(step(scope).jobs.map((item) => item.id), ["verify-G01"]);
  const tampered = readJson(file(scope, "candidates.json"));
  tampered.groups = [];
  writeJson(file(scope, "candidates.json"), tampered);
  const again = step(scope);
  assert.equal(again.stage, "verify");
  assert.deepEqual(again.jobs.map((item) => item.id), ["verify-G01"]);
  assert.equal(readJson(file(scope, "candidates.json")).groups.length, 1);
});

test("a verifier result written for an earlier merge does not bind to the renumbered groups", () => {
  const scope = scoped("renumber");
  writeJson(file(scope, "intent.json"), INTENT);
  writeFinds(scope, { "c01-correctness-p1": [candidate({ severity: "medium", locations: [{ file: "src/app.js", line: 30 }] })] });
  step(scope);
  verifierResult(scope, "G01", { status: "refuted", confidence: "high", checked: ["read src/app.js:30"], refutation: "src/app.js:29 guards it" });
  assert.equal(step(scope).stage, "review");
  writeJson(file(scope, "finds/c01-security-p1.json"), finderOutput(scope, scope.plan.jobs[1], [candidate({ lens: "security", severity: "high", title: "Token check removed", locations: [{ file: "src/app.js", line: 5 }] })]));
  const next = step(scope);
  assert.equal(next.stage, "verify");
  assert.deepEqual(next.jobs.map((item) => item.id), ["verify-G01", "verify-G02"]);
  assert.deepEqual(next.pruned, ["G01"]);
  assert.equal(fs.existsSync(file(scope, "verify/G01.result.json")), false);
});

test("a failed next removes the report of an earlier done", () => {
  const scope = scoped("stale-report");
  writeJson(file(scope, "intent.json"), INTENT);
  writeFinds(scope);
  step(scope);
  const template = readJson(file(scope, "review.template.json"));
  writeJson(file(scope, "review.json"), { ...template, verdict: "pass", run: { ...template.run, runtime: "claude-code" } });
  assert.equal(step(scope).stage, "done");
  assert.ok(fs.existsSync(file(scope, "report.json")));
  writeJson(file(scope, "review.json"), { verdict: "block" });
  assert.equal(step(scope).stage, "review");
  assert.equal(fs.existsSync(file(scope, "report.json")), false);
});

