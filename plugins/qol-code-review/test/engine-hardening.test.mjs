test("the run root defaults to a private folder under the temp folder and refuses an open override", () => {
  const home = path.join(root, "tmp-home");
  fs.mkdirSync(home);
  const before = process.env.TMPDIR;
  process.env.TMPDIR = home;
  try {
    const uid = process.getuid?.();
    const made = outRoot({});
    assert.equal(made, path.join(home, uid === undefined ? "code-review-engine" : `code-review-engine-${uid}`));
    assert.equal(fs.statSync(made).mode & 0o777, 0o700);
  } finally {
    if (before === undefined) delete process.env.TMPDIR;
    else process.env.TMPDIR = before;
  }
  const open = path.join(root, "open-override");
  fs.mkdirSync(open);
  fs.chmodSync(open, 0o755);
  const error = catching(() => outRoot({ CODE_REVIEW_ENGINE_DIR: open }));
  assert.deepEqual([error.code, error.message], [EXIT.input, `${open} is not a folder only you can open; remove it, or set CODE_REVIEW_ENGINE_DIR to another folder`]);
});

