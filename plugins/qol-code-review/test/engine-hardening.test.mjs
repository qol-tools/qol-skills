test("a head cannot hide files from review with its own attributes, markers, vendor folders or binary bytes", { skip: OLD_GIT }, () => {
  const { dir, out } = fixture("hostile-head", { "README.md": "hi\n", "src/auth/login.js": "export function login(u, p) {\n  if (!check(u, p)) throw new Error('no');\n  return token(u);\n}\n" });
  sh(dir, "checkout", "-qb", "pr");
  commit(dir, {
    ".gitattributes": "src/auth/session.js linguist-generated\nsrc/auth/login.js linguist-vendored\n",
    "src/auth/session.js": "export function session(u) { return token(u); }\n",
    "src/auth/vendor/helper.js": "export const bypass = (u) => true;\n",
    "src/auth/login.js": "// Hand written. DO NOT EDIT without review\nexport function login(u, p) {\n  return token(u);\n}\n",
    "src/auth/nul.js": "export function admin(u) { return true; } // \u0000\n",
    "README.md": "hi there\n",
  }, "pr");
  const scope = runScope("pr", { base: "main", lookupPr: false }, depsFor(dir, out));
  const byPath = Object.fromEntries(scope.files.map((file) => [file.path, file]));
  assert.deepEqual(scope.files.filter((file) => file.excluded).map((file) => [file.path, file.exclude_reason]), []);
  assert.equal(byPath["src/auth/login.js"].tier, "high");
  assert.ok(["deep", "max"].includes(scope.level.suggested), scope.level.suggested);
});

