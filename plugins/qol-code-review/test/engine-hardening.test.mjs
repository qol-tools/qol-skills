test("a new file is excluded only by its name as a lockfile or by an asset extension", () => {
  const file = (name, extra = {}) => ({ path: name, status: "A", old_path: null, hunks: [], binary: false, mode_change: false, ...extra });
  assert.equal(classifyFile(file("yarn.lock")).excluded, true);
  assert.equal(classifyFile(file("img/a.png", { binary: true })).excluded, true);
  for (const name of ["vendor/a.js", "dist/app.min.js", "src/schema.pb.go"]) assert.equal(classifyFile(file(name)).excluded, false, name);
  const blob = classifyFile(file("src/blob.js", { binary: true }));
  assert.deepEqual([blob.excluded, blob.signals.includes("binary-content")], [false, true]);
  const flipped = classifyFile(file("src/app.js", { status: "M", old_path: "src/app.js", binary: true, base_binary: false }));
  assert.deepEqual([flipped.excluded, flipped.signals.includes("text-to-binary"), flipped.tier], [false, true, "high"]);
});

test("a docs-only diff that adds a possible secret is not the trivial quick path", () => {
  const hunk = { header: "@@", old_start: 1, old_count: 0, new_start: 1, new_count: 1, context: "", lines: ['+api_key = "abcdefghijklmnop1234"'], added: 1, removed: 0 };
  const file = { path: "docs/setup.md", status: "M", old_path: "docs/setup.md", hunks: [hunk], binary: false, mode_change: false };
  const result = suggestLevel([{ ...file, ...classifyFile(file) }]);
  assert.notEqual(result.level, "quick");
  assert.equal(result.trivial, false);
});

